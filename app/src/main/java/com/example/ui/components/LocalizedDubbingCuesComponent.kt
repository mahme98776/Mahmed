/**
 * Modern Jetpack Compose UI component displaying the list of `LocalizedDubbingCue`
 * generated by the Gemini Automatic Video-to-Audio Dubbing Synthesis Service.
 *
 * Provides granular audio playback for every individual scene segment with pitch/rate adaptation,
 * live animated waveform indicators, character badge styling, script editing, and studio integration.
 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
fun LocalizedDubbingCuesComponent(
    uiState: LocalizedDubbingCuesUiState,
    onPlayCue: (LocalizedDubbingCue) -> Unit,
    onStopAudio: () -> Unit,
    onPlayAll: () -> Unit,
    onSynthesizeCue: (LocalizedDubbingCue) -> Unit,
    onUpdateScript: (cueId: String, newScript: String) -> Unit,
    onApplyToStudio: (LocalizedDubbingCue) -> Unit,
    onFilterGender: (String?) -> Unit,
    onSearchQueryChange: (String) -> Unit,
    onReloadSamples: () -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    var editingCue by remember { mutableStateOf<LocalizedDubbingCue?>(null) }

    // Dialog for editing script inline
    if (editingCue != null) {
        val targetCue = editingCue!!
        var editedScriptText by remember(targetCue) { mutableStateOf(targetCue.localizedDubbedScript) }

        AlertDialog(
            onDismissRequest = { editingCue = null },
            title = {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Icon(
                        imageVector = Icons.Default.Edit,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.primary
                    )
                    Text(
                        text = "تعديل نص الدبلجة للمقطع",
                        fontWeight = FontWeight.Bold,
                        fontSize = 16.sp
                    )
                }
            },
            text = {
                Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                    Text(
                        text = "الشخصية: ${targetCue.characterSpeakerName} (${targetCue.characterGender})",
                        fontSize = 12.sp,
                        color = MaterialTheme.colorScheme.primary,
                        fontWeight = FontWeight.SemiBold
                    )
                    Text(
                        text = "التوقيت: ${targetCue.formattedTimeRange}",
                        fontSize = 11.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    OutlinedTextField(
                        value = editedScriptText,
                        onValueChange = { editedScriptText = it },
                        label = { Text("النص العربي المدبلج") },
                        minLines = 3,
                        maxLines = 5,
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("edit_cue_script_input")
                    )
                }
            },
            confirmButton = {
                Button(
                    onClick = {
                        onUpdateScript(targetCue.id, editedScriptText)
                        editingCue = null
                        Toast.makeText(context, "تم تحديث نص المقطع بنجاح! ✨", Toast.LENGTH_SHORT).show()
                    },
                    modifier = Modifier.testTag("confirm_edit_cue_script_button")
                ) {
                    Text("حفظ التعديل")
                }
            },
            dismissButton = {
                TextButton(onClick = { editingCue = null }) {
                    Text("إلغاء")
                }
            }
        )
    }

    // Filtered Cues
    val filteredCues = remember(uiState.cues, uiState.selectedGenderFilter, uiState.searchQuery) {
        uiState.cues.filter { cue ->
            val matchesGender = uiState.selectedGenderFilter == null ||
                    cue.characterGender.equals(uiState.selectedGenderFilter, ignoreCase = true)
            val matchesSearch = uiState.searchQuery.isBlank() ||
                    cue.localizedDubbedScript.contains(uiState.searchQuery, ignoreCase = true) ||
                    cue.originalDialogue.contains(uiState.searchQuery, ignoreCase = true) ||
                    cue.characterSpeakerName.contains(uiState.searchQuery, ignoreCase = true) ||
                    cue.visualActionDescription.contains(uiState.searchQuery, ignoreCase = true)
            matchesGender && matchesSearch
        }
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(horizontal = 14.dp, vertical = 8.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        // 1. Service Analysis Header Card
        AnalysisOverviewHeaderCard(
            analysis = uiState.analysisResult,
            totalCuesCount = uiState.cues.size,
            isPlayingAll = uiState.isPlayingAll,
            onPlayAll = onPlayAll,
            onStopAudio = onStopAudio,
            onReloadSamples = onReloadSamples
        )

        // 2. Search & Gender Filter Row
        SearchAndFilterBar(
            searchQuery = uiState.searchQuery,
            onSearchQueryChange = onSearchQueryChange,
            selectedGender = uiState.selectedGenderFilter,
            onSelectGender = onFilterGender,
            cuesCount = filteredCues.size
        )

        // 3. Error Banner if any
        AnimatedVisibility(visible = uiState.errorMessage != null) {
            Surface(
                color = Color(0xFFEF4444).copy(alpha = 0.15f),
                shape = RoundedCornerShape(12.dp),
                border = BorderStroke(1.dp, Color(0xFFEF4444).copy(alpha = 0.4f)),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier.padding(12.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Icon(Icons.Default.Clear, contentDescription = null, tint = Color(0xFFEF4444))
                    Text(
                        text = uiState.errorMessage ?: "",
                        color = Color(0xFFEF4444),
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Medium
                    )
                }
            }
        }

        // 4. Loading Indicator or Cues List
        if (uiState.isLoading) {
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(260.dp),
                contentAlignment = Alignment.Center
            ) {
                Column(
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    CircularProgressIndicator(color = MaterialTheme.colorScheme.primary)
                    Text(
                        text = "جاري استخراج وتحليل توقيتات الفيديو عبر Gemini Service...",
                        fontSize = 13.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.primary
                    )
                }
            }
        } else if (filteredCues.isEmpty()) {
            EmptyCuesStateCard(
                hasFilters = uiState.searchQuery.isNotBlank() || uiState.selectedGenderFilter != null,
                onResetFilters = {
                    onSearchQueryChange("")
                    onFilterGender(null)
                },
                onLoadSample = onReloadSamples
            )
        } else {
            // LazyColumn of all LocalizedDubbingCues
            LazyColumn(
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1f)
                    .testTag("localized_cues_lazy_column"),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                itemsIndexed(
                    items = filteredCues,
                    key = { _, cue -> cue.id }
                ) { index, cue ->
                    val isPlayingThisCue = uiState.currentlyPlayingCueId == cue.id

                    LocalizedDubbingCueCard(
                        cue = cue,
                        index = index + 1,
                        isPlaying = isPlayingThisCue,
                        onPlay = { onPlayCue(cue) },
                        onStop = onStopAudio,
                        onSynthesize = { onSynthesizeCue(cue) },
                        onEdit = { editingCue = cue },
                        onApplyToStudio = { onApplyToStudio(cue) },
                        onCopyText = {
                            val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                            val clip = ClipData.newPlainText("Dubbing Script", cue.localizedDubbedScript)
                            clipboard.setPrimaryClip(clip)
                            Toast.makeText(context, "تم نسخ النص المدبلج للحافظة! 📋", Toast.LENGTH_SHORT).show()
                        }
                    )
                }
                item {
                    Spacer(Modifier.height(40.dp))
                }
            }
        }
    }
}

